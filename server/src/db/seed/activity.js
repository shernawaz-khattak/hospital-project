  await clinical.closeVisit(ahmed, aliVisit.id, 'Metformin increased, glimepiride added. Review with HbA1c.');
  // An earlier lab report for Ali (portal demo) — reported a few days ago
  {
    const test = testByCode.LFT;
    const at = new Date(Date.now() - 4 * 86400000);
    const [lr] = await knex('lab_requests').insert({ request_code: await nextCode(knex, 'lab_request_code_seq'), patient_id: patients[0].id, doctor_id: doctors['dr.ahmed'].id, visit_id: aliVisit.id, lab_test_id: test.id, urgency: 'routine', clinical_notes: 'Baseline before metformin increase', parameters: JSON.stringify(test.parameters.map((p) => p.name)), status: 'reported', technician_id: tech, started_at: at, completed_at: new Date(at.getTime() + 50 * 60000), processing_minutes: 50, created_at: new Date(at.getTime() - 3600000) }).returning('*');
    await writeLabReport(knex, { request: lr, test, patient: patients[0], values: fakeValues(test), uploadedAt: new Date(at.getTime() + 60 * 60000), techId: tech });
  }

  // Lab work in different states
  const labCtx = await ctxFor(knex, 'labtech');
  await lab.startProcessing(labCtx, tropReq.id);
  await lab.startProcessing(labCtx, hba1c.id);
