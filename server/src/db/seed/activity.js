  // Waitlist: fill Dr. Usman's next working day completely, then add two waitlisted patients
  {
    const doc = doctors['dr.usman'];
    let day = addDays(today, 1);
    while (!(await knex('doctor_schedules').where({ doctor_id: doc.id, weekday: weekdayOf(day) }).first())) day = addDays(day, 1);
    const { slots } = await appts.getSlots(doc.id, day);
    let k = 0;
    for (const s of slots.filter((x) => x.available)) {
      for (let tries = 0; tries < patients.length; tries++) {
        const patient = patients[(k++ + 3) % patients.length];
        try {
          await appts.book(reception, { patientId: patient.id, doctorId: doc.id, date: day, startTime: s.startTime, reason: 'Orthopaedic review' });
          break;
        } catch { /* try next patient */ }
      }
    }
    await appts.addToWaitlist(reception, { patientId: patients[10].id, doctorId: doc.id, preferredDate: day, notes: 'Knee pain, prefers morning' }).catch(() => {});
    await appts.addToWaitlist(reception, { patientId: patients[18].id, doctorId: doc.id, preferredDate: day, notes: 'Post-fracture follow-up' }).catch(() => {});
  }

  // Admissions (active): through the service so beds update and doctors are notified.
  const admit = async (patient, wardName, doctorUser, reason, daysAgo) => {
    const ward = wards[wardName];
    const bed = await knex('beds').where({ ward_id: ward.id, status: 'available' }).orderBy('bed_number').first();
    const docRow = doctors[doctorUser];
    const adm = await wardsSvc.admit(reception, { patientId: patient.id, wardId: ward.id, bedId: bed.id, attendingDoctorId: docRow.id, reason });
    const at = new Date(Date.now() - daysAgo * 86400000);
    await knex('admissions').where({ id: adm.id }).update({ admitted_at: at });
    await knex('visits').where({ admission_id: adm.id }).update({ started_at: at });
    return adm;
  };
  const admHamza = await admit(patients[2], 'Cardiac Care Unit', 'dr.sara', 'Unstable angina, for monitoring', 2);
  const admRabia = await admit(patients[5], 'Maternity Ward', 'dr.ayesha', 'Pre-term contractions at 32 weeks', 1);
  const admImran = await admit(patients[10], 'Surgical Ward', 'dr.usman', 'Right knee arthroscopy', 3);
  await admit(patients[4], 'Pediatric Ward', 'dr.bilal', 'Acute tonsillitis with dehydration', 0);

  // Clinical notes for admitted patients (service calls)
  const sara = await ctxFor(knex, 'dr.sara');
  const usman = await ctxFor(knex, 'dr.usman');
  const ayesha = await ctxFor(knex, 'dr.ayesha');
  const hamzaVisit = await knex('visits').where({ admission_id: admHamza.id }).first();
  await clinical.addObservation(sara, hamzaVisit.id, { temperatureC: 37.0, pulseBpm: 96, systolicBp: 150, diastolicBp: 95, spo2: 96, symptoms: 'Chest discomfort at rest, relieved by GTN' });
  await clinical.addDiagnosis(sara, hamzaVisit.id, { conditionName: 'Unstable angina', icdCode: 'I20.0', severity: 'severe', notes: 'Known CAD with stent; troponin pending' });
  const rxHamza = await clinical.createPrescription(sara, hamzaVisit.id, { items: [{ medicineId: medByName['Disprin CV'].id, dosage: '75 mg', frequency: 'Once daily', durationDays: 30, quantity: 30 }, { medicineId: medByName['Lipitor'].id, dosage: '20 mg', frequency: 'Once at night', durationDays: 30, quantity: 30 }], acknowledgeWarnings: true });
  const tropReq = await clinical.requestLabTest(sara, { patientId: patients[2].id, visitId: hamzaVisit.id, labTestId: testByCode.TROP.id, urgency: 'stat', clinicalNotes: 'Rule out NSTEMI' });
  await clinical.requestLabTest(sara, { patientId: patients[2].id, visitId: hamzaVisit.id, labTestId: testByCode.LIPID.id, urgency: 'routine', clinicalNotes: 'Secondary prevention review', specialInstructions: 'Fasting sample tomorrow morning' });

  const imranVisit = await knex('visits').where({ admission_id: admImran.id }).first();
  await clinical.addDiagnosis(usman, imranVisit.id, { conditionName: 'Osteoarthritis right knee, post arthroscopy', icdCode: 'M17.1', severity: 'moderate', notes: 'Day 2 post-op, wound clean, mobilising with frame' });
  const rxImran = await clinical.createPrescription(usman, imranVisit.id, { items: [{ medicineId: medByName['Brufen'].id, dosage: '400 mg', frequency: 'Three times daily after food', durationDays: 5, quantity: 15 }, { medicineId: medByName['Losec'].id, dosage: '20 mg', frequency: 'Once daily before breakfast', durationDays: 5, quantity: 5 }] });
  await wardsSvc.approveDischarge(usman, admImran.id, 'Recovering well; can be discharged once the final bill is settled.');

  const rabiaVisit = await knex('visits').where({ admission_id: admRabia.id }).first();
  await clinical.addDiagnosis(ayesha, rabiaVisit.id, { conditionName: 'Threatened pre-term labour', icdCode: 'O60.0', severity: 'severe', notes: 'Contractions settled with rest; fetal heart reassuring' });
  await clinical.requestLabTest(ayesha, { patientId: patients[5].id, visitId: rabiaVisit.id, labTestId: testByCode.CBC.id, urgency: 'urgent', clinicalNotes: 'Pre-term contractions, check for infection' });
  const uaReq = await clinical.requestLabTest(ayesha, { patientId: patients[5].id, visitId: rabiaVisit.id, labTestId: testByCode.UA.id, urgency: 'routine', clinicalNotes: 'Exclude UTI' });

  // An outpatient consultation for Ali Hassan earlier today, with a pending prescription and lab test
  const ahmed = await ctxFor(knex, 'dr.ahmed');
  const aliVisit = await clinical.startVisit(ahmed, { patientId: patients[0].id, visitType: 'emergency', chiefComplaint: 'High blood sugar readings at home' });
  await clinical.addObservation(ahmed, aliVisit.id, { temperatureC: 36.8, pulseBpm: 84, systolicBp: 142, diastolicBp: 88, bloodGlucose: 248, weightKg: 82, symptoms: 'Polyuria, thirst' });
  await clinical.addDiagnosis(ahmed, aliVisit.id, { conditionName: 'Type 2 diabetes mellitus — poorly controlled', icdCode: 'E11.65', severity: 'moderate', notes: 'HbA1c due; adjust therapy' });
  const rxAli = await clinical.createPrescription(ahmed, aliVisit.id, { items: [{ medicineId: medByName['Glucophage'].id, dosage: '1000 mg', frequency: 'Twice daily with meals', durationDays: 30, quantity: 60 }, { medicineId: medByName['Amaryl'].id, dosage: '2 mg', frequency: 'Once daily before breakfast', durationDays: 30, quantity: 30 }] });
